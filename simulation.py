def generate_live_case(
    base_case: SimulationCase,
    *,
    api_key: str,
    model: str | None = None,
) -> SimulationCase:
    """Generate fresh customer copy while retaining fixture-backed case truth."""

    if not api_key.strip():
        raise ValueError("An OpenAI API key is required to generate a live incident.")
    try:
        from openai import OpenAI
    except ImportError as exc:  # pragma: no cover - optional dependency
        raise RuntimeError("Install the OpenAI SDK with: python -m pip install openai") from exc
    client = OpenAI(api_key=api_key)
    response = client.responses.parse(
        model=model or os.getenv("OPENAI_MODEL", "gpt-5.4-mini"),
        input=[
            {"role": "system", "content": CASE_COPY_INSTRUCTIONS},
            {"role": "user", "content": base_case.model_dump_json()},
        ],
        text_format=GeneratedCaseCopy,
        store=False,
    )
    generated = response.output_parsed
    if generated is None:
        raise RuntimeError("The model returned no generated incident.")
    return base_case.model_copy(
        deep=True,
        update={
            **generated.model_dump(),
            "case_id": f"case-live-{base_case.template_id}-{uuid4().hex[:6]}",
        },
    )


def submit_free_text(
    session: TrainingSession,
    trainee_message: str,
    simulator: CustomerSimulator | None = None,
) -> CustomerEvaluation:
    """Send a trainee-authored message and apply the customer reaction safely."""

    message = trainee_message.strip()
    if not message:
        raise ValueError("Write a response before sending it.")
    engine = simulator or MockCustomerSimulator()
    session.conversation.append(
        ConversationMessage(role=ConversationRole.SUPPORT, content=message)
    )
    evaluation = engine.respond(session, message)
    session.conversation.append(
        ConversationMessage(role=ConversationRole.CUSTOMER, content=evaluation.reply)
    )
    session.score = max(0, min(100, session.score + evaluation.score_delta))
    session.customer_mood = evaluation.customer_mood
    session.attempts += 1
    session.last_feedback = evaluation.feedback
    session.events.append(
        SimulationEvent(
            event_type="free_text_evaluation",
            summary=evaluation.feedback,
            detail={
                "score_delta": evaluation.score_delta,
                "engine": engine.name,
                "advance": evaluation.advance,
            },
        )
    )
    if evaluation.advance:
        _advance(session)
    return evaluation


def score_band(score: int) -> tuple[str, str]:
    if score >= 90:
        return "Expert", "Excellent evidence discipline and customer ownership."
    if score >= 70:
        return "Strong", "Good triage with a few opportunities to be more precise."
    if score >= 45:
        return "Developing", "The case progressed, but some choices added risk or delay."
    return "Needs work", "Revisit discovery, evidence boundaries and owned next actions."


