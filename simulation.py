def utc_now_iso() -> str:
    return datetime.now(timezone.utc).isoformat()


class TrainingPhase(str, Enum):
    DISCOVERY = "discovery"
    DIAGNOSIS = "diagnosis"
    RESPONSE = "response"
    COMPLETE = "complete"


class ConversationRole(str, Enum):
    CUSTOMER = "customer"
    SUPPORT = "support"
    SYSTEM = "system"


class ConversationMessage(StrictModel):
    role: ConversationRole
    content: str
    created_at: str = Field(default_factory=utc_now_iso)


class SimulationCase(StrictModel):
    template_id: str
    case_id: str
    title: str
    company: str
    contact_name: str
    contact_role: str
    priority: str
    difficulty: str
    sla_minutes: int
    category: str
    customer_tone: str
    initial_message: str
    discovery_prompt: str
    discovery_reply: str
    confirmed_identifiers: dict[str, str | int]
    diagnostic_tool: str
    diagnostic_arguments: dict[str, Any]
    resolution: str
    escalation_required: bool = False
    coach_note: str


class SupportChoice(StrictModel):
    choice_id: str
    label: str
    kind: str
    feedback: str
    score_delta: int
    is_best: bool = False
    advances: bool = False
    customer_reply: str
    tool_name: str | None = None
    tool_arguments: dict[str, Any] = Field(default_factory=dict)


class SimulationEvent(StrictModel):
    event_type: str
    summary: str
    created_at: str = Field(default_factory=utc_now_iso)
    detail: dict[str, Any] = Field(default_factory=dict)


class TrainingSession(StrictModel):
    case: SimulationCase
    phase: TrainingPhase = TrainingPhase.DISCOVERY
    score: int = 0
    customer_mood: str = "Concerned"
    customer_patience: int = 3
    attempts: int = 0
    conversation: list[ConversationMessage] = Field(default_factory=list)
    tool_results: list[ToolResult] = Field(default_factory=list)
    events: list[SimulationEvent] = Field(default_factory=list)
    last_feedback: str | None = None
    outcome: str | None = None
    started_at: str = Field(default_factory=utc_now_iso)
    completed_at: str | None = None

    @classmethod
    def start(cls, case: SimulationCase) -> "TrainingSession":
        return cls(
            case=case,
            conversation=[
                ConversationMessage(
                    role=ConversationRole.CUSTOMER,
                    content=case.initial_message,
                )
            ],
            events=[
                SimulationEvent(
                    event_type="case_arrived",
                    summary=f"{case.priority} case received from {case.company}",
                )
            ],
        )


class CustomerEvaluation(StrictModel):
    reply: str
    score_delta: int = Field(ge=-25, le=40)
    feedback: str
    advance: bool = False
    customer_mood: str = "Concerned"


