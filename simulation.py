CASE_BY_TEMPLATE = {case.template_id: case for case in CASE_TEMPLATES}


def _fresh_case(case: SimulationCase) -> SimulationCase:
    return case.model_copy(
        deep=True,
        update={"case_id": f"case-{case.template_id}-{uuid4().hex[:6]}"},
    )


def build_incoming_queue(*, count: int = 4, seed: int | None = None) -> list[SimulationCase]:
    """Build a varied queue without changing the underlying fixture truth."""

    rng = random.Random(seed)
    cases = list(CASE_TEMPLATES)
    rng.shuffle(cases)
    if count > len(cases):
        cases = [cases[index % len(cases)] for index in range(count)]
    else:
        cases = cases[:count]
    return [_fresh_case(case) for case in cases]


def _choice(
    case: SimulationCase,
    phase: TrainingPhase,
    slug: str,
    label: str,
    *,
    feedback: str,
    score_delta: int,
    customer_reply: str,
    is_best: bool = False,
    advances: bool = False,
    tool_name: str | None = None,
    tool_arguments: dict[str, Any] | None = None,
) -> SupportChoice:
    return SupportChoice(
        choice_id=f"{case.template_id}-{phase.value}-{slug}",
        label=label,
        kind=phase.value,
        feedback=feedback,
        score_delta=score_delta,
        customer_reply=customer_reply,
        is_best=is_best,
        advances=advances,
        tool_name=tool_name,
        tool_arguments=tool_arguments or {},
    )


