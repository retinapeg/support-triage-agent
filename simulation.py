"""Interactive support-engineering training simulation.

The simulator puts the human trainee in the decision loop.  Customer language
may be generated by a hosted model, but operational truth stays grounded in the
same synthetic fixture IDs used by the diagnostic tools.  This keeps the demo
convincing without allowing a model to invent logs or claim a remediation ran.
"""

