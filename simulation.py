def _diagnosis_choices(case: SimulationCase) -> list[SupportChoice]:
    identifiers = case.confirmed_identifiers
    status_code = int(identifiers.get("http_status", 500))
    candidates = [
        _choice(
            case,
            TrainingPhase.DIAGNOSIS,
            "correct-tool",
            f"Run {case.diagnostic_tool} with {json.dumps(case.diagnostic_arguments)} and inspect the returned evidence.",
            feedback="Correct diagnostic: it uses a customer-supplied identifier and tests the boundary most likely to separate causes.",
            score_delta=35,
            customer_reply="Understood. I’ll wait for what the trace actually shows.",
            is_best=True,
            advances=True,
            tool_name=case.diagnostic_tool,
            tool_arguments=case.diagnostic_arguments,
        ),
        _choice(
            case,
            TrainingPhase.DIAGNOSIS,
            "status-page",
            "Check only the aggregate service-status page and stop if it is green.",
            feedback="A green aggregate status does not rule out a request-specific, credential or customer-endpoint failure.",
            score_delta=-4,
            customer_reply="The status page is green, but our exact failure is still happening. Can you trace the identifier we supplied?",
            tool_name="check_service_status",
        ),
        _choice(
            case,
            TrainingPhase.DIAGNOSIS,
            "http-definition",
            f"Look up the generic meaning of HTTP {status_code} without inspecting the supplied request or event.",
            feedback="Reference semantics help, but they do not establish what happened to this customer’s operation.",
            score_delta=-3,
            customer_reply="That explains the code in general, but what does your trace show for our specific failure?",
            tool_name="lookup_http_status",
            tool_arguments={"code": status_code},
        ),
        _choice(
            case,
            TrainingPhase.DIAGNOSIS,
            "docs-only",
            "Search a general troubleshooting article and send it to the customer without tracing the case.",
            feedback="Documentation is not a substitute for inspecting the supplied correlation identifier.",
            score_delta=-5,
            customer_reply="We have read the general guide. We need you to connect it to our request or event.",
            tool_name="search_internal_docs",
            tool_arguments={"query": f"{case.category} troubleshooting"},
        ),
        _choice(
            case,
            TrainingPhase.DIAGNOSIS,
            "assume-fixed",
            "Assume the retry worked, mark the issue resolved and close the case.",
            feedback="Unsupported resolution: no diagnostic evidence or customer confirmation shows recovery.",
            score_delta=-18,
            customer_reply="The issue is not resolved. Please do not close this until you have checked the evidence.",
        ),
    ]
    # When the correct diagnostic is one of the generic candidates, keep exactly
    # one best option and replace the duplicate with a clearly irrelevant path.
    filtered: list[SupportChoice] = []
    seen_tools: set[str] = set()
    for item in candidates:
        if item.tool_name and item.tool_name in seen_tools:
            continue
        filtered.append(item)
        if item.tool_name:
            seen_tools.add(item.tool_name)
    if len(filtered) < 5:
        filtered.append(
            _choice(
                case,
                TrainingPhase.DIAGNOSIS,
                "credential-reset",
                "Tell the customer to rotate every credential before checking whether authentication is involved.",
                feedback="A disruptive credential rotation is not justified by the evidence gathered so far.",
                score_delta=-10,
                customer_reply="Before we rotate production credentials, can you show that authentication is actually the failing boundary?",
            )
        )
    return filtered[:5]


def _response_choices(case: SimulationCase) -> list[SupportChoice]:
    best_label = (
        f"Escalate with the confirmed evidence and tell the customer: {case.resolution}"
        if case.escalation_required
        else f"Give an evidence-bounded resolution: {case.resolution}"
    )
    return [
        _choice(
            case,
            TrainingPhase.RESPONSE,
            "evidence-bound",
            best_label,
            feedback="Strong close: it separates confirmed evidence from scope, owns the next action and avoids claiming an unverified fix.",
            score_delta=40,
            customer_reply=(
                "That is clear. Please keep ownership of the escalation and the next update."
                if case.escalation_required
                else "That gives us a concrete, safe next step. We’ll apply it and return with a new identifier if the issue continues."
            ),
            is_best=True,
            advances=True,
        ),
        _choice(
            case,
            TrainingPhase.RESPONSE,
            "global-fix",
            "Say the root cause is confirmed globally and the incident is now fixed for every customer.",
            feedback="The evidence supports only this inspected case and does not prove a global root cause or recovery.",
            score_delta=-18,
            customer_reply="How did you confirm a global fix? We have not yet reported recovery.",
        ),
        _choice(
            case,
            TrainingPhase.RESPONSE,
            "blame",
            "Tell the customer the problem is entirely their fault and close the ticket.",
            feedback="Blame is unnecessary and the close removes ownership before remediation is verified.",
            score_delta=-15,
            customer_reply="That is not an acceptable handoff. What does the evidence show and who owns the next step?",
        ),
        _choice(
            case,
            TrainingPhase.RESPONSE,
            "raw-logs",
            "Paste all available raw logs into the reply without explaining scope, evidence or next steps.",
            feedback="Raw output without interpretation is not a customer-ready resolution and may expose unnecessary data.",
            score_delta=-10,
            customer_reply="Can you translate this into the finding, what we should do, and when you will update us?",
        ),
        _choice(
            case,
            TrainingPhase.RESPONSE,
            "wait",
            "Ask the customer to wait indefinitely without an owner, action or update time.",
            feedback="A response needs explicit ownership and a next action or update cadence.",
            score_delta=-12,
            customer_reply="Who owns this now, and when should we expect the next update?",
        ),
    ]


def choices_for(session: TrainingSession) -> list[SupportChoice]:
    if session.phase == TrainingPhase.DISCOVERY:
        choices = _discovery_choices(session.case)
    elif session.phase == TrainingPhase.DIAGNOSIS:
        choices = _diagnosis_choices(session.case)
    elif session.phase == TrainingPhase.RESPONSE:
        choices = _response_choices(session.case)
    else:
        return []
    seed_material = f"{session.case.case_id}:{session.phase.value}:{session.attempts}"
    seed = int(hashlib.sha256(seed_material.encode()).hexdigest()[:16], 16)
    random.Random(seed).shuffle(choices)
    return choices


def _set_mood(session: TrainingSession, delta: int) -> None:
    if delta >= 20:
        session.customer_mood = "Reassured"
    elif delta > 0:
        session.customer_mood = "Cooperative"
    elif delta <= -15:
        session.customer_mood = "Alarmed"
    else:
        session.customer_mood = "Frustrated"


def _advance(session: TrainingSession) -> None:
    if session.phase == TrainingPhase.DISCOVERY:
        session.phase = TrainingPhase.DIAGNOSIS
    elif session.phase == TrainingPhase.DIAGNOSIS:
        session.phase = TrainingPhase.RESPONSE
    elif session.phase == TrainingPhase.RESPONSE:
        session.phase = TrainingPhase.COMPLETE
        session.completed_at = utc_now_iso()
        session.outcome = "Escalated with evidence" if session.case.escalation_required else "Customer given a safe resolution"


def apply_choice(
    session: TrainingSession,
    choice_id: str,
    simulator: CustomerSimulator | None = None,
) -> SupportChoice:
    """Apply one of the five visible actions and record its consequence."""

    choices = {choice.choice_id: choice for choice in choices_for(session)}
    if choice_id not in choices:
        raise ValueError("That action is not available for the current stage.")
    choice = choices[choice_id]
    session.attempts += 1
    session.score = max(0, min(100, session.score + choice.score_delta))
    session.last_feedback = choice.feedback
    session.conversation.append(
        ConversationMessage(role=ConversationRole.SUPPORT, content=choice.label)
    )

    result: ToolResult | None = None
    if choice.tool_name:
        result = dispatch_tool(choice.tool_name, choice.tool_arguments)
        session.tool_results.append(result)
        session.events.append(
            SimulationEvent(
                event_type="tool_result",
                summary=result.summary,
                detail={
                    "tool_name": choice.tool_name,
                    "arguments": choice.tool_arguments,
                    "success": result.success,
                },
            )
        )

    customer_reply = choice.customer_reply
    if simulator is not None and simulator.name == "openai":
        reaction = simulator.respond(session, choice.label)
        customer_reply = reaction.reply
        session.events.append(
            SimulationEvent(
                event_type="live_customer_reaction",
                summary="Customer reaction generated by the configured OpenAI model.",
                detail={"engine": simulator.name},
            )
        )
    session.conversation.append(
        ConversationMessage(role=ConversationRole.CUSTOMER, content=customer_reply)
    )
    session.events.append(
        SimulationEvent(
            event_type="decision",
            summary=choice.feedback,
            detail={
                "choice_id": choice.choice_id,
                "score_delta": choice.score_delta,
                "best": choice.is_best,
            },
        )
    )
    _set_mood(session, choice.score_delta)
    if choice.advances and (result is None or result.success):
        _advance(session)
    return choice


class CustomerSimulator(Protocol):
    name: str

    def respond(self, session: TrainingSession, trainee_message: str) -> CustomerEvaluation:
        """React as the customer and assess the trainee response."""


